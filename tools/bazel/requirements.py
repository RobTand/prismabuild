"""Export or check pip.parse's hashed requirements from the hosted gate's pins.

tools/ci/gate_requirements.txt is what every hosted gate shard installs, so it
is the source of truth. The export resolves it once, with hashes, for Linux
x86_64 and aarch64, as of a recorded date so it reproduces. --check needs no
network: the export must name the current source's sha256 and pin every
package the source pins at the same version.
"""
import argparse
import importlib.util
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = 'tools/ci/gate_requirements.txt'
EXPORT = 'tools/bazel/requirements.txt'
FIX = 'python3 tools/bazel/requirements.py'
EXCLUDE_NEWER = '2026-11-02T00:00:00Z'
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)', re.MULTILINE)


def normal(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def pins(text):
    return {normal(name): version for name, version in PIN.findall(text)}


def _digests():
    """PrismaBuild's one digest owner, loaded by path like the gate selector does."""
    spec = importlib.util.spec_from_file_location('requirements_digests', ROOT / 'src/prismabuild/digest_primitives.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def header(source):
    digest = _digests().raw_sha256(source.encode())
    return (f'# Generated by {FIX} from {SOURCE}; do not edit.\n'
            f'# source-sha256: {digest}\n# exclude-newer: {EXCLUDE_NEWER}\n')


def problems(source, export):
    """Why the export no longer matches the source; empty when it does."""
    found = []
    if not export.startswith(header(source)):
        found.append(f'{EXPORT} was not generated from the current {SOURCE}')
    exported = pins(export)
    for name, version in sorted(pins(source).items()):
        if exported.get(name) != version:
            found.append(f'{SOURCE} pins {name}=={version}; {EXPORT} has {exported.get(name)}')
    return found


def export(source_path):
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary, 'requirements.txt')
        subprocess.run(['uv', 'pip', 'compile', str(source_path), '--universal', '--generate-hashes',
                        '--python-version', '3.14', '--exclude-newer', EXCLUDE_NEWER,
                        '--no-header', '--no-annotate', '--quiet', '--output-file', str(output)],
                       check=True)
        return output.read_text()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    source = (args.root / SOURCE).read_text()
    if args.check:
        found = problems(source, (args.root / EXPORT).read_text())
        if found:
            sys.exit('Bazel requirements drifted:\n' + '\n'.join(found) + f'\nFix: {FIX}')
        return 0
    (args.root / EXPORT).write_text(header(source) + export(args.root / SOURCE))
    return 0


if __name__ == '__main__':
    sys.exit(main())
