#!/usr/bin/env python3
"""Write every generated BUILD.bazel from PrismaBuild's own dependency evidence.

Gazelle can't express PrismaBuild's imports: test modules import other test
modules (a py_test can't be a dependency), import cycles exist, conftest sets
sys.path roots at run time, and modules load other modules by path. The merge
gate's static selector already reads all of these, so this generator turns the
same evidence (tools/ci/gate_select.py, tools/ci/gate_paths.py) into targets:

- one py_library per module, and one per import cycle;
- one pb_py_test per test file, depending on its module's library;
- data for every file a module names by path;
- tags from the hosted gate's population: a test file outside it is manual,
  tagged with its lane or owning issue, and keeps its node-level deselects.

Run tools/bazel/generate.sh after adding a module, test or fixture. --check
fails, naming each file, when a generated BUILD.bazel differs, is missing, is
no longer generated, or is not tracked by git.
"""
