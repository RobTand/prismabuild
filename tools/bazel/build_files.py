#!/usr/bin/env python3
"""Write every generated BUILD.bazel from PrismaBuild's own dependency evidence.

Gazelle can't express PrismaBuild's imports: test modules import other test
modules (a py_test can't be a dependency), import cycles exist, conftest sets
sys.path roots at run time, and modules load other modules by path. The merge
gate's static selector already reads all of these, so this generator turns the
same evidence (tools/ci/gate_select.py, tools/ci/gate_paths.py) into targets:

- one py_library per module, and one per import cycle;
- one pb_py_test per test file, depending on its module's library;
- data for every file a module names by path;
- tags from the hosted gate's population: a test file outside it is manual,
  tagged with its lane or owning issue, and keeps its node-level deselects.

Run tools/bazel/generate.sh after adding a module, test or fixture. --check
fails, naming each stale file, when a committed BUILD.bazel differs.
"""
from __future__ import annotations

import argparse
import ast
from collections import defaultdict
import importlib.util
import json
import math
import os
import posixpath
import re
from pathlib import Path, PurePosixPath
import subprocess
import sys
import textwrap

ROOT = Path(__file__).resolve().parents[2]
FIX = 'tools/bazel/generate.sh'
HEADER = '# Generated by tools/bazel/generate.sh from PrismaBuild\'s dependency evidence. Do not edit.\n'
# Bazel packages that hold modules. Every other file belongs to the root
# package. tools/bazel is written by hand. tools is one package because an
# import cycle joins tools/fleet and tools/maintenance.
PACKAGES = ('src/prismabuild', 'tools', 'tests')
HANDWRITTEN = ('tools/bazel/',)
CONFTESTS = ('conftest.py', 'tests/conftest.py')
TREE_LABEL = re.compile(r'"//([\w/]*):files(/[\w./-]+)?"')
IMPORT_LINE = re.compile(r'^\s*(import\s+[A-Za-z_][\w.]*|from\s+[A-Za-z_.][\w.]*\s+import\s+[\w*(])')
# A string naming a module, as gate_select reads one.
MODULE_NAME = re.compile(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*')
# Directories that are never inputs: VCS metadata and Bazel's own output links.
SKIPPED = ('.git/', 'bazel-')
# What a glob must never pick up: BUILD files, and what Bazel, the gate and
# Python write into a checkout (all ignored by .gitignore).
GLOB_EXCLUDE = ['**/BUILD.bazel', 'bazel-*/**', '*bazel-remote-grpc.log', '*execution_log.binpb.zst',
                'gate-artifacts/**', 'gate-output/**', '**/__pycache__/**', '**/*.pyc']
# Files longer than this on hosted runners are split across Bazel test shards.
SHARD_SECONDS = 40.0
MAX_SHARDS = 8


def sibling_names(tree):
    """Literal file names passed to .with_name(...); gate_paths keeps only their directory."""
    return {node.args[0].value for node in ast.walk(tree)
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
            and node.func.attr == 'with_name' and node.args
            and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)}


def import_from_path(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def repository_files(root):
    """Tracked and untracked, unignored files: a new test counts before `git add`."""
    output = subprocess.run(['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard'],
                            cwd=root, capture_output=True, check=True).stdout.decode()
    # BUILD files define the graph; no test reads them, and leaving them out
    # keeps generation a fixed point.
    return sorted(path for path in set(output.split('\0')) if path and not path.startswith(SKIPPED)
                  and PurePosixPath(path).name != 'BUILD.bazel'
                  and (root / path).is_file() and not (root / path).is_symlink())


def package_of(path):
    if path.startswith(HANDWRITTEN):
        return HANDWRITTEN[0].rstrip('/')
    for package in PACKAGES:
        if path.startswith(package + '/'):
            return package
    return ''


def is_module(path):
    return path.endswith('.py') and not path.startswith(HANDWRITTEN) and (
        path == 'conftest.py' or path.startswith(('src/prismabuild/', 'tools/', 'tests/')))


def is_test(path):
    return path.startswith('tests/') and PurePosixPath(path).name.startswith('test_') and path.endswith('.py')


def is_test_side(path):
    return path.startswith('tests/') or path == 'conftest.py'


def strongly_connected(nodes, edges):
    """Tarjan's algorithm, iterative. Returns components in a stable order."""
    index, low, on_stack, stack, components = {}, {}, set(), [], []
    counter = 0
    for start in sorted(nodes):
        if start in index:
            continue
        work = [(start, iter(sorted(edges.get(start, ()))))]
        index[start] = low[start] = counter
        counter += 1
        stack.append(start)
        on_stack.add(start)
        while work:
            node, children = work[-1]
            advanced = False
            for child in children:
                if child not in index:
                    index[child] = low[child] = counter
                    counter += 1
                    stack.append(child)
                    on_stack.add(child)
                    work.append((child, iter(sorted(edges.get(child, ())))))
                    advanced = True
                    break
                if child in on_stack:
                    low[node] = min(low[node], index[child])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                component = []
                while True:
                    member = stack.pop()
                    on_stack.discard(member)
                    component.append(member)
                    if member == node:
                        break
                components.append(sorted(component))
    return sorted(components)


class Evidence:
    """Each module's library edges and the files it reads, from its source.

    Library edges come from import statements anywhere in the file (inside
    functions too), imports in embedded `python -c` snippets, literal
    import_module and __import__ names, pytest_plugins entries and, in tests,
    exact paths to src/ and tools/ modules: a test that runs a tool by path
    needs the tool's imports. A bare string is not an import, and a path to a
    test file or a glob is data, never an edge.

    Data comes from tools/ci/gate_paths.py's path references, read from the
    repository root (see referenced).
    """

    def __init__(self, root, files, gate_select, gate_paths):
        self.root, self.files, self.file_set = root, files, set(files)
        self.gate_select, self.gate_paths = gate_select, gate_paths
        self.build_files = {f'{package}/BUILD.bazel'.lstrip('/') for package in ('', *PACKAGES, HANDWRITTEN[0].rstrip('/'))}
        self.modules = sorted(path for path in files if is_module(path))
        self.aliases = defaultdict(set)
        for path in self.modules:
            for alias in module_aliases(gate_select, path):
                self.aliases[alias].add(path)
        self.facts = {path: self.read(path) for path in self.modules}

    def read(self, path):
        """(module names, loader paths, path references, with_name siblings) of one file."""
        tree = ast.parse((self.root / path).read_text())
        trees = [tree] + [snippet for node in ast.walk(tree)
                          if isinstance(node, ast.Constant) and isinstance(node.value, str) and 'import ' in node.value
                          for snippet in parse_snippets(node.value)]
        names, loaders = set(), set()
        for each in trees:
            names |= imported_names(each, path)
            dynamic, loaded = self.gate_select.production_loads(each, path)
            names |= dynamic
            loaders |= loaded
        references = set().union(*(self.gate_paths.references(each, path) for each in trees))
        return names, loaders, references, sibling_names(tree)

    def imported(self, name):
        parts = name.split('.')
        found = set()
        for end in range(1, len(parts) + 1):
            found.update(self.aliases.get('.'.join(parts[:end]), ()))
        return found

    def referenced(self, references):
        """(files named exactly, files a pattern matches), from the repository root.

        A bare directory names nothing, as in gate_select: conftest names src
        only to put it on sys.path. '**/X' is X under a base the analyzer
        couldn't resolve, such as a root passed in as a parameter; it is read
        as the repository path X, not matched anywhere, so tmp_path tails like
        '**/cas' name nothing. '**/**' and '**/' carry no path at all. A test
        that reads a repository file it didn't declare finds it missing on the
        remote executor.
        """
        anchored = set()
        for reference in references:
            if reference.startswith('**/'):
                reference = reference[3:]
                if reference in ('', '**'):
                    continue
            anchored.add(reference)
        # A package's BUILD file can be named exactly; patterns never match one.
        builds = {reference for reference in anchored if reference in self.build_files}
        if '**' in anchored:
            return builds, set(self.files)
        exact = builds | {reference for reference in anchored if reference in self.file_set}
        patterns = {reference for reference in anchored if '**' in reference}
        matched = {path for path in self.files if self.gate_paths.matches(path, patterns)} if patterns else set()
        return exact, matched - exact

    def of(self, path):
        """(modules this module needs as libraries, files it reads)."""
        names, loaders, references, siblings = self.facts[path]
        modules = set().union(*(self.imported(name) for name in names)) if names else set()
        if is_test_side(path):
            exact, matched = self.referenced(references)
            modules |= {file for file in exact if is_module(file) and not is_test_side(file)}
            # conftest's patterns name the collected test files, which each
            # test declares, and the live store; only its exact paths are inputs.
            data = exact if path in CONFTESTS else exact | matched
        else:
            exact, matched = self.referenced(loaders)
            modules |= {file for file in exact | matched if is_module(file) and not is_test_side(file)}
            data = self.production_reads(path, references, siblings)
        modules.discard(path)
        # Data may repeat a module's own sources; runfiles hold each file once,
        # and a whole directory stays one filegroup.
        return modules, data

    def production_reads(self, path, references, siblings):
        """The files production module `path` reads for every caller: exact files
        and siblings named with Path(__file__).with_name.

        Its tree reads (docs/**, src/prismabuild/**, */**) come from publishing,
        scanning and source bundling. They are inputs only of tests that import
        the module themselves (tree_reads); on the library they'd reach every
        test, because conftest imports modules that do them.
        """
        exact = self.referenced({reference for reference in references if not wildcard(reference)})[0]
        named = {posixpath.join(posixpath.dirname(path), name) for name in siblings}
        trees = set().union(*(self.referenced({name + '/**'})[1] for name in named)) if named else set()
        return exact | (named & self.file_set) | trees

    def tree_reads(self, path):
        """Files that production module `path` reads through patterns."""
        references = self.facts[path][2]
        return set().union(*self.referenced({reference for reference in references if wildcard(reference)}))

    def test_modules(self, path):
        """Modules a test file names in a string, such as a parametrized list it
        imports by name. They are that test's inputs and never propagate: other
        tests that import this test module don't run its tests."""
        tree = ast.parse((self.root / path).read_text())
        found = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and MODULE_NAME.fullmatch(node.value):
                found |= self.imported(node.value)
        found.discard(path)
        return found

    def test_data(self, path, modules):
        """A test file's own extra inputs: the tree reads of the production
        modules it imports directly, so the test that exercises a scanner has
        what it scans. They sit on the test target and never propagate."""
        return set().union(*(self.tree_reads(module) for module in modules if not is_test_side(module))) \
            if modules else set()


def module_aliases(gate_select, path):
    """gate_select's names, plus every dotted suffix of a tools/ or tests/ module:
    conftest and tests put directories such as tools/fleet on sys.path, so
    tools/fleet/pbcanary_legs/leg3.py is also pbcanary_legs.leg3."""
    names = set(gate_select.module_names(path))
    if path.startswith(('tools/', 'tests/')):
        parts = path.removesuffix('.py').split('/')
        if parts[-1] == '__init__':
            parts = parts[:-1]
        names.update('.'.join(parts[start:]) for start in range(len(parts)))
    return names


def wildcard(reference):
    return '*' in reference.removeprefix('**/') or '?' in reference


def parse_snippets(text):
    """Python embedded in a string: a `-c` argument or a script a test writes.

    The whole text when it parses after dedenting; otherwise each import line
    alone, which also covers the literal pieces of an f-string.
    """
    try:
        return [ast.parse(textwrap.dedent(text))]
    except (SyntaxError, ValueError):
        pass
    found = []
    for line in text.splitlines():
        if IMPORT_LINE.match(line):
            try:
                # The statement only: an f-string piece may stop mid-call after ';'.
                found.append(ast.parse(line.split(';', 1)[0].strip()))
            except (SyntaxError, ValueError):
                continue
    return found


def imported_names(tree, path):
    """Every module an import statement or pytest_plugins entry names, as gate_select resolves them."""
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            prefix = node.module or ''
            if node.level:
                package = list(PurePosixPath(path.removeprefix('src/')).parent.parts)
                package = package[:len(package) - node.level + 1]
                prefix = '.'.join([*package, *([prefix] if prefix else [])])
            if prefix:
                names.add(prefix)
            names.update(f'{prefix}.{alias.name}' if prefix else alias.name for alias in node.names)
        elif isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == 'pytest_plugins'
                                                  for target in node.targets):
            names.update(value.value for value in ast.walk(node.value)
                         if isinstance(value, ast.Constant) and isinstance(value.value, str))
    return names


def analyse(root, files):
    gate_select = import_from_path('gate_select', root / 'tools/ci/gate_select.py')
    return gate_select, Evidence(root, files, gate_select, gate_select.gate_paths)


class GenerationError(RuntimeError):
    """The evidence can't become a valid Bazel graph. Generation fails."""


def relative(path, package):
    return path[len(package) + 1:] if package else path


def library_name(path):
    stem = relative(path, package_of(path)).removesuffix('.py')
    # The test target takes the file's name; its importable module needs another.
    return stem + '_lib' if is_test(path) else stem


def label(package, name, home):
    return f':{name}' if package == home else f'//{package}:{name}'


def file_label(path, home):
    package = package_of(path)
    return relative(path, package) if package == home else f'//{package}:{relative(path, package)}'


class Trees:
    """Name a set of files by the fewest labels: a directory whose every file is
    in the set becomes one glob filegroup in its package."""

    def __init__(self, files):
        self.under = defaultdict(set)
        for path in files:
            package = package_of(path)
            parts = PurePosixPath(relative(path, package)).parts
            for end in range(len(parts)):
                self.under[(package, '/'.join(parts[:end]))].add(path)
        self.used = defaultdict(set)

    def labels(self, files, home):
        remaining, labels = set(files), set()
        for (package, directory), members in sorted(self.under.items(), key=lambda item: item[0][1].count('/')
                                                     + bool(item[0][1])):
            if package == HANDWRITTEN[0].rstrip('/') and directory:
                continue
            if len(members) > 1 and members <= remaining:
                remaining -= members
                self.used[package].add(directory)
                labels.add(label(package, tree_name(directory), home))
        return sorted(labels | {file_label(path, home) for path in remaining})


def tree_name(directory):
    return 'files/' + directory if directory else 'files'


def strings(values, indent='        '):
    if not values:
        return '[]'
    return '[\n' + ''.join(f'{indent}{json.dumps(value)},\n' for value in values) + indent[:-4] + ']'


def hosted_plan(gate_select, root, evidence):
    """The hosted gate's full-mode plan: who runs, who doesn't and why."""
    # The population needs only the module names.
    index = {path: (set(), set()) for path in evidence.modules
             if path.startswith(('tests/', 'src/prismabuild/', 'tools/'))}
    durations = json.loads((root / 'tools/ci/gate_durations.json').read_text())
    plan = gate_select.create_plan(root, [], durations=durations,
                                   quarantine=json.loads((root / 'tools/ci/gate_quarantine.json').read_text()),
                                   index=index, mode='full')
    return plan, durations['files']


def test_attributes(path, plan, durations):
    """args, tags, shard_count and timeout for one test file."""
    selected = {row['path'] for row in plan['selected']}
    attributes = {}
    if path in selected:
        attributes['args'] = ['--deselect=' + node for node in plan['deselect']
                              if node.split('::', 1)[0] == path]
    else:
        reasons = [row for row in plan['deferred'] if row['path'] == path]
        if not reasons:
            raise GenerationError(f'{path} is neither in the gate population nor deferred')
        tags = ['manual']
        for row in reasons:
            tags.append(f"gate-lane-{row['lane']}" if row.get('lane') else f"gate-issue-{row['issue']}")
        attributes['tags'] = sorted(set(tags))
    seconds = durations.get(path)
    if seconds is not None and seconds > SHARD_SECONDS:
        shards = min(MAX_SHARDS, math.ceil(seconds / SHARD_SECONDS))
        attributes['shard_count'] = shards
        seconds /= shards
    attributes['timeout'] = 'long' if seconds is not None and seconds * 3 > 300 else 'moderate'
    return attributes


def generate(root=ROOT, files=None):
    """{package directory: BUILD.bazel text} for every generated package."""
    files = repository_files(root) if files is None else files
    gate_select, evidence = analyse(root, files)
    edges, data = {}, {}
    for path in evidence.modules:
        edges[path], data[path] = evidence.of(path)
    owner, libraries = {}, []
    for component in strongly_connected(evidence.modules, edges):
        packages = {package_of(path) for path in component}
        if len(packages) > 1:
            raise GenerationError('an import cycle crosses Bazel packages, which no target can hold: '
                                  + ', '.join(component))
        name = library_name(component[0]) + ('_cycle' if len(component) > 1 else '')
        for path in component:
            owner[path] = (packages.pop() if len(packages) else package_of(path), name)
        libraries.append(component)
    plan, durations = hosted_plan(gate_select, root, evidence)
    trees = Trees(files)
    # Filegroups tools/bazel/test_inputs.bzl names must exist.
    for package, directory in TREE_LABEL.findall((root / 'tools/bazel/test_inputs.bzl').read_text()):
        trees.used[package].add(directory.removeprefix('/'))
    packages = {package: [] for package in ('', *PACKAGES)}
    for component in libraries:
        home, name = owner[component[0]]
        deps = sorted({label(*owner[target], home) for path in component for target in edges[path]}
                      - {label(home, name, home)})
        inputs = trees.labels({file for path in component for file in data[path]}, home)
        packages[home].append((name, 'pb_py_library', {
            'srcs': [relative(path, home) for path in component], 'data': inputs, 'deps': deps}))
    for path in evidence.modules:
        if is_test(path):
            home = package_of(path)
            packages[home].append((relative(path, home).removesuffix('.py'), 'pb_py_test', {
                'path': path, 'library': label(*owner[path], home),
                'deps': sorted({label(*owner[module], home) for module in evidence.test_modules(path)}
                               - {label(*owner[path], home)}),
                'data': trees.labels(evidence.test_data(path, edges[path]), home),
                **test_attributes(path, plan, durations)}))
    for package, directories in trees.used.items():
        if package == HANDWRITTEN[0].rstrip('/'):
            continue  # Its BUILD file, written by hand, declares :files.
        for directory in directories:
            pattern = directory + '/**' if directory else '**'
            packages[package].append((tree_name(directory), 'filegroup', {
                'srcs': f'glob([{json.dumps(pattern)}], exclude = {json.dumps(GLOB_EXCLUDE)})'}))
    return {package: render_package(package, targets) for package, targets in packages.items()}


def render_package(package, targets):
    names = [name for name, _, _ in targets]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise GenerationError(f'two targets named {duplicates} in //{package}; rename a module')
    kinds = sorted({kind for _, kind, _ in targets} - {'filegroup'})
    lines = [HEADER]
    if kinds:
        lines.append('load("//tools/bazel:python.bzl", ' + ', '.join(f'"{kind}"' for kind in kinds) + ')\n')
    lines.append('package(default_visibility = ["//visibility:public"])\n')
    lines.append('# Other packages name these files as test data.\n'
                 f'exports_files(glob(["**"], exclude = {json.dumps(GLOB_EXCLUDE)}))\n')
    for name, kind, attributes in sorted(targets):
        body = [f'    name = {json.dumps(name)},\n']
        for key, value in attributes.items():
            if value in ([], None):
                continue
            rendered = (strings(value) if isinstance(value, list) else
                        value if key == 'srcs' else json.dumps(value))
            body.append(f'    {key} = {rendered},\n')
        lines.append(f'{kind}(\n' + ''.join(body) + ')\n')
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    try:
        generated = generate(args.root)
    except GenerationError as error:
        sys.exit(f'Cannot generate BUILD files: {error}')
    stale = []
    for package, text in sorted(generated.items()):
        path = args.root / package / 'BUILD.bazel'
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(args.root)))
        else:
            path.write_text(text)
    if stale:
        sys.exit('Generated BUILD files are stale: ' + ', '.join(stale) + f'\nFix: {FIX}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
