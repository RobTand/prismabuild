# Bazel packages that hold modules. Every other file belongs to the root
# package. tools/bazel is written by hand. tools is one package because an
# import cycle joins tools/fleet and tools/maintenance.
PACKAGES = ('src/prismabuild', 'tools', 'tests')
HANDWRITTEN = ('tools/bazel/',)
CONFTESTS = ('conftest.py', 'tests/conftest.py')
TREE_LABEL = re.compile(r'"//([\w/]*):files(/[\w./-]+)?"')
IMPORT_LINE = re.compile(r'^\s*(import\s+[A-Za-z_][\w.]*|from\s+[A-Za-z_.][\w.]*\s+import\s+[\w*(])')
# Calls that import a module named at run time.
NAME_IMPORTERS = frozenset({'import_module', '__import__', 'spec_from_file_location', 'SourceFileLoader',
                            'run_path', 'run_module'})
# A string naming a module, as gate_select reads one.
MODULE_NAME = re.compile(r'[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*')
# Directories that are never inputs: VCS metadata and Bazel's own output links.
SKIPPED = ('.git/', 'bazel-')
# What a glob must never pick up: BUILD files, and what Bazel, the gate and
